DATE_RX = re.compile(r"^(\d{1,2})[.\-/](\d{1,2})[.\-/](\d{2}|\d{4})$")
ROLE_ORDER = ["разраб", "пров", "т.контр", "н.контр", "утв"]


def _date(s: str):
    m = DATE_RX.match((s or "").strip())
    if not m:
        return "bad"
    d, mo, y = int(m.group(1)), int(m.group(2)), int(m.group(3))
    y += 2000 if y < 100 else 0
    try:
        return dt.date(y, mo, d)
    except ValueError:
        return "bad"


def check_title_ext(drw: Drawing) -> None:
    t = drw.title
    if not t.found:
        return
    seen: set = set()
    name = (t.name or "").strip()
    pg, bb = drw.first_page if hasattr(drw, "first_page") else 0, t.bboxes.get("name")
    if name:
        if name[0].islower() or name.endswith(".") or re.search(r"ГОСТ|\bдет\.|\bсб\.", name):
            once(drw, seen, "C601", "x", f"Наименование «{name}»: начинайте с заглавной буквы, без точки в конце и без ссылок на стандарты", pg, bb)
    lit = (t.litera or "").strip()
    if lit and (re.search(r"[A-Za-z]|[а-я]", lit) or len(lit) > 3):
        once(drw, seen, "C603", lit, f"Литера «{lit}»: русские заглавные буквы и цифра («О», «О1», «А»)", pg, t.bboxes.get("litera"))
    if lit:
        for part in re.split(r"[\s,;/]+", lit.translate(str.maketrans("AOT", "АОТ"))):
            if part and not re.fullmatch(r"[ПЭТАБИ]|О\d{0,2}", part) and not re.search(r"[A-Za-z]|[а-я]", part) and len(part) <= 3:
                once(drw, seen, "C616", part, f"Литера «{part}» не предусмотрена ГОСТ 2.103: П, Э, Т, О, О1…Оn, А, Б, И", pg, t.bboxes.get("litera"))
    n_pages = len(drw.pages)
    sheets = (t.sheets or "").strip()
    if not sheets and not drw.ocr:
        once(drw, seen, "C617", "x", "Графа «Листов» не заполнена", pg, t.bboxes.get("sheets"))
    if sheets.isdigit():
        if n_pages == 1 and int(sheets) >= 1:
            once(drw, seen, "C604", sheets, f"«Листов {sheets}» на однолистовом документе: графы листов не заполняют", pg, t.bboxes.get("sheets"))
        if n_pages > 1 and int(sheets) != n_pages:
            once(drw, seen, "C605", sheets, f"«Листов {sheets}», а в файле {n_pages} лист(ов)", pg, t.bboxes.get("sheets"))
    dates = {}
    for role, s in (t.dates or {}).items():
        if not s:
            continue
        d = _date(s)
        if d == "bad":
            once(drw, seen, "C606", s, f"Дата «{s}» ({role}): ожидается «дд.мм.гг» и существующая дата", pg, bb)
        else:
            dates[role.lower()] = d
            if d > dt.date.today() + dt.timedelta(days=30):
                once(drw, seen, "C608", s, f"Дата «{s}» ({role}) позже сегодняшней", pg, bb)
    prev = None
    for key in ROLE_ORDER:
        for role, d in dates.items():
            if role.startswith(key):
                if prev and d < prev[1]:
                    once(drw, seen, "C607", (key, role), f"Дата «{role}» ({d:%d.%m.%y}) раньше даты «{prev[0]}» ({prev[1]:%d.%m.%y})", pg, bb)
                else:
                    prev = (role, d)
                break
    for role, s in (t.people or {}).items():
        if s and (re.search(r"[A-Za-z]|\d", s)):
            once(drw, seen, "C609", s, f"Фамилия «{s}» ({role}): русские буквы без цифр", pg, bb)
    if not (t.organization or "").strip():
        once(drw, seen, "C610", "x", "Графа 9 (предприятие) не заполнена", pg, bb)
    des = (t.designation or "").strip()
    if des and t.first_use and t.first_use.strip() == des:
        once(drw, seen, "C611", des, f"«Перв. примен.» совпадает с обозначением изделия «{des}»", pg, t.bboxes.get("first_use"))
    nums = []
    for ch in t.changes or []:
        m = re.search(r"\d+", str(ch.get("num", "")))
        if m:
            nums.append(int(m.group(0)))
    if len(nums) >= 2 and nums != list(range(nums[0], nums[0] + len(nums))):
        once(drw, seen, "C612", "x", f"Номера изменений в таблице: {', '.join(map(str, nums))} — идут не подряд", pg, bb)
    mat = (t.material or "").strip()
    if des:
        if re.search(r"СБ$", des) and mat:
            once(drw, seen, "C613", des, f"На сборочном чертеже {des} указан материал «{mat}»", pg, t.bboxes.get("material"))
        if re.fullmatch(r"[А-ЯA-Z]{4}\.\d{6}\.\d{3}", des) and not mat:
            once(drw, seen, "C614", des, f"У детали {des} не указан материал (графа 3)", pg, bb)
    fmt = (t.format or "").replace(" ", "").upper()
    sc = re.match(r"^(\d+):(\d+)$", (t.scale or "").replace(" ", ""))
    if sc:
        a, b = int(sc.group(1)), int(sc.group(2))
        if (fmt.startswith("А4") and b >= 10 and a == 1) or (fmt.startswith(("А0", "A0")) and a >= 5 and b == 1):
            once(drw, seen, "C615", fmt, f"Формат {fmt} и масштаб {t.scale}: сочетание нетипично", pg, t.bboxes.get("scale"))


def check_title_pack(drw: Drawing) -> None:
    run_all(drw, (check_title_ext,))
