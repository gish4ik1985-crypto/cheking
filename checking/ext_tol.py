def _dim_tol(d) -> float | None:
    if d.upper is not None and d.lower is not None:
        return round(d.upper - d.lower, 4)
    f = d.field or d.fit_shaft or d.fit_hole
    if f and d.nominal:
        return _field_tol(d.nominal, f)
    return None


def _near_dim(drw: Drawing, ln, maxd: float = 25.0):
    best, bd = None, maxd
    cx, cy = (ln.bbox[0] + ln.bbox[2]) / 2, (ln.bbox[1] + ln.bbox[3]) / 2
    for d in drw.dims:
        if d.page != ln.page or d.kind not in ("diameter", "linear") or not d.nominal or _dim_tol(d) is None:
            continue
        x, y = (d.bbox[0] + d.bbox[2]) / 2, (d.bbox[1] + d.bbox[3]) / 2
        dist = ((x - cx) ** 2 + (y - cy) ** 2) ** 0.5
        if dist < bd:
            best, bd = d, dist
    return best


