def general_tol(cls: str, size: float) -> float | None:
    if size < 0.5:
        return None
    for i, (_, hi) in enumerate(LIN_IV):
        if size <= hi:
            return LIN[cls][i]
    return None


def _plain(d) -> bool:
    return not (d.upper_raw or d.lower_raw or d.field or d.fit_hole or d.fit_shaft or d.reference or d.symmetric or d.chain)


def tt_text(drw: Drawing) -> str:
    items = drw.facts.get("_tt_items") or [(t, None, None) for t in drw.tt]
    return " ".join(t for t, _, _ in items)


def _loc(drw: Drawing):
    items = drw.facts.get("_tt_items") or []
    return (items[0][1], items[0][2]) if items else (None, None)


def classes(drw: Drawing) -> tuple[set, set]:
    """(классы линейных допусков f/m/c/v, классы формы и расположения H/K/L) из ссылок на ГОСТ 30893."""
    t = tt_text(drw)
    lin = set(re.findall(r"30893\.1\s*[-–:]?\s*([fmcv])\b", t))
    form = set()
    for m in re.finditer(r"30893\.2\s*[-–]\s*(?:([fmcv])([HKL])|([HKL]))\b", t):
        if m.group(1):
            lin.add(m.group(1))
        form.add(m.group(2) or m.group(3))
    return lin, form


