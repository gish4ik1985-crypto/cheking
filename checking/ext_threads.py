def check_drill(drw: Drawing) -> None:
    seen: set = set()
    for t, pg, bb in texts(drw):
        if not re.search(r"(?i)под\s+резьб|резьб", t):
            continue
        dm = re.search(r"[⌀Ø∅]\s?(\d+(?:[.,]\d+)?)", t)
        for th in threads_in_text(t):
            if not dm:
                break
            x = to_float(dm.group(1))
            d, p = th["d"], th["p"]
            if p is None:
                e = METRIC_THREADS.get(d)
                p = e[0] if e else None
            if x is None or p is None or x >= d:
                continue
            d1 = d - 1.0825 * p
            if abs(x - d1) > 0.35:
                once(drw, seen, "I111", t[:40], f"«{t.strip()[:60]}»: внутренний диаметр М{fmtn(d)}"
                     f"{'×' + fmtn(p) if th['p'] else ''} равен {d1:.2f} мм, а отверстие ⌀{fmtn(x)} — проверьте", pg, bb)


def threads_in_text(t: str) -> list[dict]:
    out = []
    for m in METRIC.finditer(t):
        d = to_float(m.group("d"))
        if d:
            out.append({"d": d, "p": to_float(m.group("p"))})
    return out


