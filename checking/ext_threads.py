def check_8724(drw: Drawing) -> None:
    seen: set = set()
    per_d: dict[float, set] = {}
    for th in threads(drw):
        d, p = th["d"], th["p"]
        k = (d, p)
        if d not in METRIC_THREADS:
            continue
        per_d.setdefault(d, set()).add(p)
        if d in ROW2:
            once(drw, seen, "I101", d, f"«{th['raw']}»: диаметр {fmtn(d)} мм — 2-й ряд ГОСТ 8724-2002; 1-й ряд предпочтительнее",
                 th["page"], th["bbox"])
        elif d not in ROW1 and d >= 1:
            once(drw, seen, "I102", d, f"«{th['raw']}»: диаметр {fmtn(d)} мм — 3-й (наименее предпочтительный) ряд "
                 f"ГОСТ 8724-2002", th["page"], th["bbox"])
        if p == 3 and d in (30, 33):
            once(drw, seen, "I103", k, f"«{th['raw']}»: шаг 3 мм у диаметра {fmtn(d)} мм в таблице ГОСТ 8724-2002 "
                 f"стоит в скобках — по возможности не применяйте", th["page"], th["bbox"])
        if d == 14 and p == 1.25:
            once(drw, seen, "I104", k, f"«{th['raw']}»: резьба М14×1,25 применяется только для свечей зажигания",
                 th["page"], th["bbox"])
        if d == 35 and p == 1.5:
            once(drw, seen, "I105", k, f"«{th['raw']}»: резьба М35×1,5 применяется только для стопорных гаек шарикоподшипников",
                 th["page"], th["bbox"])
        if re.search(r"\bлев(?:ая|ый|ое|\.)|\bЛ\.\s*Н", th["text"], re.I) and "LH" not in th["text"]:
            once(drw, seen, "I106", th["raw"], f"«{th['text'].strip()[:50]}»: левую резьбу обозначают буквами LH — "
                 f"«{th['raw']}-LH»", th["page"], th["bbox"])
        ph, p_ = th["ph"], th["p"]
        if ph and p_:
            n = ph / p_
            if abs(n - round(n)) > 1e-6:
                once(drw, seen, "I107", th["raw"], f"«{th['raw']}»: ход {fmtn(ph)} не кратен шагу {fmtn(p_)} — число "
                     f"заходов {n:.2f} не целое", th["page"], th["bbox"])
        if th["p2"] and p_:
            once(drw, seen, "I108", th["raw"], f"«{th['raw']}»: многозаходную метрическую резьбу записывают через "
                 f"ход и шаг — «М{fmtn(d)}×Ph{fmtn(p_)}P{fmtn(th['p2'])}»", th["page"], th["bbox"])
    for th in threads(drw):
        if th["d"] < 1:
            once(drw, seen, "I109", th["d"], f"«{th['raw']}»: резьбу диаметром менее 1 мм обозначают по ГОСТ 9000",
                 th["page"], th["bbox"])
    for d, ps in per_d.items():
        ps = {x for x in ps}
        if len(ps) > 1:
            once(drw, seen, "I110", d, f"Резьба диаметром {fmtn(d)} мм записана с разными шагами "
                 f"({', '.join('крупный' if x is None else fmtn(x) for x in sorted(ps, key=lambda v: (v is None, v)))}) — проверьте")


