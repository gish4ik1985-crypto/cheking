# ------------------------------------------------------------------------------------------------ разбор ---
_NUM = r"\d+(?:[.,]\d+)?"
METRIC = re.compile(
    rf"(?<![A-Za-zА-Яа-я0-9])[МM]\s?(?P<d>{_NUM})"
    rf"(?:\s*[×xх]\s*(?:Ph\s?(?P<ph>{_NUM})\s?P\s?)?(?P<p>{_NUM})(?:\s*\(\s*[PР]\s*(?P<p2>{_NUM})\s*\))?)?"
    rf"(?P<tail>(?:\s*[-–]\s*[0-9A-Za-z/()]+)*)")
EXT_FIELD = re.compile(r"^(?P<a>\d)(?P<la>[d-h])(?:(?P<b>\d)(?P<lb>[d-h]))?$")
INT_FIELD = re.compile(r"^(?P<a>\d)(?P<la>[E-H])(?:(?P<b>\d)(?P<lb>[E-H]))?$")
RECOMMENDED_EXT = {"3h4h", "4g", "4h", "5h4h", "5g6g", "5h6h", "6d", "6e", "6f", "6g", "6h", "7e6e", "7g6g", "7h6h",
                   "8e", "8g", "9e8e", "9g8g"}
RECOMMENDED_INT = {"4H", "5H", "6H", "5G", "6G", "7G", "7H", "8G", "8H"}


def threads(drw: Drawing) -> list[dict]:
    out = []
    for t, pg, bb in texts(drw):
        for m in METRIC.finditer(t):
            d = to_float(m.group("d"))
            if not d or d > 700:
                continue
            tail = [x.strip() for x in re.split(r"\s*[-–]\s*", m.group("tail") or "") if x.strip()]
            out.append({"raw": m.group(0).strip(), "d": d, "p": to_float(m.group("p")), "ph": to_float(m.group("ph")),
                        "p2": to_float(m.group("p2")), "tail": tail, "page": pg, "bbox": bb, "text": t})
    return out


def _fields(tail: list[str]) -> list[str]:
    return [x for x in tail if re.match(r"^\d[A-Za-z]", x)]


