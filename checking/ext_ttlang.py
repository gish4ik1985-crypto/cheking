_WORD = re.compile(r"[А-Яа-яЁё]+(?:-[А-Яа-яЁё]+)*")


def _norm(w: str) -> str:
    return w.lower().replace("ё", "е")


@lru_cache(maxsize=1)
def _lexicon():
    """(множество слов, множество основ, основы по окончаниям, варианты основ с одной удалённой буквой)."""
    from . import catalog, rule_docs
    texts = [str(r[2]) for r in catalog.RULES] + list(SEED)
    for d in rule_docs.RULE_DOCS.values():
        texts.extend(str(x) for x in d.values())
    words = {_norm(w) for t in texts for w in re.findall(r"[А-Яа-яЁё]{7,}", t)}
    stems: set[str] = set()
    by_end: dict[str, set[str]] = {}
    dels: dict[str, dict[str, str]] = {}
    for w in words:
        s, e = w[:-3], w[-3:]
        stems.add(s)
        by_end.setdefault(e, set()).add(s)
        d = dels.setdefault(e, {})
        for i in range(len(s)):
            d.setdefault(s[:i] + s[i + 1:], s)
    return words, stems, by_end, dels


def _suggest(word: str) -> str | None:
    """Слово словаря, от которого `word` отличается одной лишней, пропущенной или переставленной буквой в основе."""
    w = _norm(word)
    if len(w) < 7:
        return None
    if w in KNOWN_TYPOS:
        return KNOWN_TYPOS[w]
    words, stems, by_end, dels = _lexicon()
    if w in words or w[:-3] in stems:
        return None
    e, t = w[-3:], w[:-3]
    known = by_end.get(e)
    if not known:
        return None
    for i in range(len(t)):                                   # лишняя буква
        if t[:i] + t[i + 1:] in known:
            return t[:i] + t[i + 1:] + e
    if t in dels.get(e, {}):                                  # пропущенная буква
        return dels[e][t] + e
    for i in range(len(t) - 1):                               # перестановка соседних букв
        if t[i] != t[i + 1] and t[:i] + t[i + 1] + t[i] + t[i + 2:] in known:
            return t[:i] + t[i + 1] + t[i] + t[i + 2:] + e
    return None


def _items(drw: Drawing) -> list:
    return drw.facts.get("_tt_items") or [(t, None, None) for t in drw.tt]


def _short(t: str, n: int = 70) -> str:
    t = t.strip()
    return t if len(t) <= n else t[:n].rstrip() + "…"


def check_period(drw: Drawing) -> None:
    for t, pg, bb in _items(drw):
        s = t.strip()
        if len(s) < 6 or not re.match(r"^\d{1,2}[.)]?\s", s):
            continue
        if re.search(r"[:;,.]$", s) or not re.search(r"[А-Яа-яЁёA-Za-z0-9)°%»\"]$", s):
            continue
        emit(drw, "P101", f"Пункт ТТ «{_short(s)}» не заканчивается точкой", pg, bb)


def check_spelling(drw: Drawing) -> None:
    seen: set = set()
    for t, pg, bb in _items(drw):
        for m in _WORD.finditer(t):
            w = m.group(0)
            if w.isupper() or "-" in w:
                continue
            fix = _suggest(w)
            if fix:
                once(drw, seen, "P102", _norm(w), f"В ТТ слово «{w}»: возможно, опечатка — «{fix}»", pg, bb)


def check_punctuation(drw: Drawing) -> None:
    seen: set = set()
    for t, pg, bb in _items(drw):
        if re.search(r"[А-Яа-яЁёA-Za-z)]\s+[,;:](?=\s|$)", t):
            once(drw, seen, "P103", ("sp", t), f"В пункте ТТ «{_short(t)}» перед знаком препинания стоит пробел", pg, bb)
        if re.search(r"[А-Яа-яЁё][,;][А-Яа-яЁё]", t):
            once(drw, seen, "P103", ("ns", t), f"В пункте ТТ «{_short(t)}» после запятой или точки с запятой нет пробела", pg, bb)
        m = re.search(r"\b([А-Яа-яЁё]{2,})\s+\1\b", t, re.I)
        if m:
            once(drw, seen, "P103", ("dup", t), f"В пункте ТТ «{_short(t)}» слово «{m.group(1)}» повторено подряд", pg, bb)


def check_ttlang_ext(drw: Drawing) -> None:
    run_all(drw, (check_period, check_spelling, check_punctuation))
