SCALE_TXT = re.compile(r"(?<![A-Za-zА-Яа-я0-9])(?P<m>[MМ])\s*(?P<a>\d+(?:[.,]\d+)?)\s*:\s*(?P<b>\d+(?:[.,]\d+)?)(?![\d])")


def check_scales_formats(drw: Drawing) -> None:
    seen: set = set()
    for ln in drw.lines:
        t = ln.text.strip()
        if len(t) > 14 or ln.page is None:
            continue
        m = SCALE_TXT.search(t)
        if not m:
            continue
        if m.group("m") == "M":
            once(drw, seen, "B101", t, f"«{t}»: перед масштабом русская «М», а не латинская M", ln.page, ln.bbox)
        elif re.match(r"[МM]\s+\d", t):
            once(drw, seen, "B101", t, f"«{t}»: между «М» и масштабом пробела нет", ln.page, ln.bbox)
        if "." in m.group("a") or "." in m.group("b"):
            once(drw, seen, "B102", t, f"«{t}»: дробная часть масштаба — запятая", ln.page, ln.bbox)
    fmt = (drw.title.format or "").replace(" ", "").upper().replace("A", "А")
    if fmt == "А4":
        for p in drw.pages:
            if p.width > p.height + 1:
                once(drw, seen, "B103", p.number, f"Формат А4, а лист расположен горизонтально ({p.width:.0f}×{p.height:.0f}): "
                     f"А4 применяют только вертикально", p.number, None)
                break


