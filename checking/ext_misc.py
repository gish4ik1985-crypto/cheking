DES1643 = re.compile(r"(?<![\d.,×xх/])(?P<n>(?:\d{1,2}|N)(?:\s*-\s*(?:\d{1,2}|N)){0,2})\s*-\s*(?P<s>[A-Za-zА-ЯЁ])(?P<t>[a-zа-я])?(?![A-Za-zА-Яа-я0-9])")
CYR_FIT = set("АВСЕНД")


def check_1643(drw: Drawing) -> None:
    seen: set = set()
    from .gears import parse_tables, _num
    cands = []
    for t, pg, bb in texts(drw):
        if re.search(r"1643", t) or re.search(r"(?i)степень\s+точност", t):
            cands.append((t, pg, bb))
    for tb in parse_tables(drw):
        pr = tb["params"].get("precision")
        if pr and not tb["spline"]:
            cands.append((pr["value"], tb["page"], pr["line"].bbox))
    name = (getattr(drw.title, "name", "") or "").lower()
    for t, pg, bb in cands:
        for m in DES1643.finditer(t):
            nums = [int(x) for x in re.findall(r"\d+", m.group("n"))]
            parts = re.findall(r"\d+|N", m.group("n"))
            raw = m.group(0).strip()
            if len(parts) == 2:
                once(drw, seen, "Z101", raw, f"«{raw}»: в обозначении одна степень или три, а не две", pg, bb)
            if any(n in (1, 2) for n in nums):
                once(drw, seen, "Z102", raw, f"«{raw}»: степени 1 и 2 ГОСТ 1643-81 не нормирует", pg, bb)
            if len(parts) in (1, 3) and all(x.isdigit() for x in parts):
                k_, p_, c_ = (int(parts[0]),) * 3 if len(parts) == 1 else tuple(int(x) for x in parts)
                if not k_ - 2 <= p_ <= k_ + 1:
                    once(drw, seen, "Z108", raw, f"«{raw}»: степень по плавности {p_} при кинематической {k_} — допускается от {k_ - 2} до {k_ + 1}", pg, bb)
                if c_ > p_ + 1:
                    once(drw, seen, "Z109", raw, f"«{raw}»: степень по контакту {c_} грубее плавности {p_} более чем на 1", pg, bb)
                rng = {"A": (3, 12), "B": (3, 11), "C": (3, 9), "D": (3, 8), "E": (3, 7), "H": (3, 7)}
                sl = m.group("s").translate(str.maketrans("АВСЕН", "ABCEH"))
                if sl in rng and not rng[sl][0] <= p_ <= rng[sl][1]:
                    once(drw, seen, "Z110", raw, f"«{raw}»: для сопряжения {sl} степень по плавности {rng[sl][0]}…{rng[sl][1]}, указано {p_}", pg, bb)
            tl = m.group("t")
            if tl and tl in "асх":                       # русские двойники строчных a, c, x
                once(drw, seen, "Z104", raw, f"«{raw}»: вид допуска «{tl}» набран русской буквой — нужна латинская", pg, bb)
                tl = tl.translate(str.maketrans("асх", "acx"))
            if tl and tl not in "xyzabcdh":
                once(drw, seen, "Z103", raw, f"«{raw}»: вида допуска «{tl}» на боковой зазор нет (x, y, z, a, b, c, d, h)", pg, bb)
            if m.group("s") in CYR_FIT:
                once(drw, seen, "Z104", raw, f"«{raw}»: вид сопряжения «{m.group('s')}» набран русской буквой — нужна латинская", pg, bb)
        joined = t
        if re.search(r"1643", joined):
            if re.search(r"коническ|гипоид", name + " " + joined, re.I):
                once(drw, seen, "Z105", "k", f"Коническую или гипоидную передачу выполняют по ГОСТ 1758-81, а не по ГОСТ 1643-81", pg, bb)
            if re.search(r"червя|червяч", name + " " + joined, re.I):
                once(drw, seen, "Z105", "w", f"Червячную передачу выполняют по ГОСТ 3675-81, а не по ГОСТ 1643-81", pg, bb)
    ref = any(re.search(r"1643", t) for t, _, _ in texts(drw))
    if ref:
        for tb in parse_tables(drw):
            if tb["spline"]:
                continue
            p = tb["params"]
            m, d, b = _num(p.get("m")), _num(p.get("d")), None
            for r in tb["rows"]:
                if re.search(r"(?i)^ширина\s+(?:зубчатого\s+)?венц", r["label"]):
                    mm = re.search(_NUM, r["value"])
                    b = to_float(mm.group(0)) if mm else None
            if m is not None and (m < 1 or m > 55):
                once(drw, seen, "Z106", m, f"Модуль {fmtn(m)} мм вне области применения ГОСТ 1643-81 (1…55 мм)"
                     + ("; для мелких модулей — ГОСТ 9178-81" if m < 1 else ""), tb["page"], tb["bbox"])
            if (d is not None and d > 6300) or (b is not None and b > 1250):
                once(drw, seen, "Z107", d or b, f"d = {fmtn(d) if d else '—'}, b = {fmtn(b) if b else '—'}: вне области "
                     f"применения ГОСТ 1643-81 (d ≤ 6300, b ≤ 1250)", tb["page"], tb["bbox"])


