PARAM = re.compile(r"(?<![A-Za-zА-Яа-я0-9])(?P<p>[RrРр](?:[AaАа]|[ZzZz]|[Mm][AaАа][XxХх]))(?=\s*[\d=≤≥<>(])")
VAL = re.compile(rf"(?<![A-Za-zА-Яа-я0-9])(?P<p>Ra|Rz|Rmax)\s*[=≤]?\s*(?P<v>{_NUM})(?![\d,]*\s*%)")


def _default_l(param: str, v: float) -> float:
    steps = [(0.025, 0.08), (0.4, 0.25), (3.2, 0.8), (12.5, 2.5), (100, 8)] if param == "Ra" else \
            [(0.1, 0.08), (1.6, 0.25), (12.5, 0.8), (50, 2.5), (400, 8)]
    for hi, l in steps:
        if v <= hi + 1e-9:
            return l
    return 8


def check_2789(drw: Drawing) -> None:
    seen: set = set()
    for t, pg, bb in texts(drw):
        for m in PARAM.finditer(t):
            p = m.group("p")
            if p not in ("Ra", "Rz", "Rmax"):
                once(drw, seen, "R101", p, f"«{t.strip()[:50]}»: параметр «{p}» — нужно «Ra», «Rz» или «Rmax» латиницей",
                     pg, bb)
        if re.search(rf"\bR[azA]\w*\s*{_NUM}\s*мм\b|\bRmax\s*{_NUM}\s*мм\b", t):
            once(drw, seen, "R102", t[:30], f"«{t.strip()[:50]}»: шероховатость задают в микрометрах, не в миллиметрах", pg, bb)
        if len(t) <= 60:
            vals = {}
            for m in VAL.finditer(t):
                v = to_float(m.group("v"))
                if v is not None:
                    vals.setdefault(m.group("p"), v)
            if "Ra" in vals and "Rz" in vals and vals["Rz"] < vals["Ra"]:
                once(drw, seen, "R103", t, f"«{t.strip()}»: Rz = {fmtn(vals['Rz'])} меньше Ra = {fmtn(vals['Ra'])}", pg, bb)
            if "Rz" in vals and "Rmax" in vals and vals["Rmax"] < vals["Rz"]:
                once(drw, seen, "R103", t, f"«{t.strip()}»: Rmax = {fmtn(vals['Rmax'])} меньше Rz = {fmtn(vals['Rz'])}", pg, bb)
        for m in re.finditer(rf"(?<![A-Za-zА-Яа-я])(?:Sm|S)\s*[=≤]?\s*({_NUM})(?!\s*(?:мкм|%|[A-Za-zА-Яа-я]))", t):
            if re.search(r"Ra|Rz|Rmax|Sm", t) and not re.search(r"(?<![A-Za-z])S\s*=\s*\d.*(?:мм2|мм²)", t):
                v = to_float(m.group(1))
                if v is not None and not 0.002 <= v <= 12.5 and m.group(0).strip().startswith("Sm"):
                    once(drw, seen, "R104", m.group(0), f"«{m.group(0).strip()}»: Sm вне диапазона 0,002…12,5 мм", pg, bb)
        if PARAM.search(t) or re.search(r"Ra|Rz|Rmax", t):
            ml = re.search(rf"(?<![A-Za-zА-Яа-я])l\s*=\s*({_NUM})", t)
            if ml:
                l = to_float(ml.group(1))
                if l is not None and not any(abs(l - x) < 1e-9 for x in (0.01, 0.03, 0.08, 0.25, 0.8, 2.5, 8, 25)):
                    once(drw, seen, "R105", ml.group(0), f"«{t.strip()[:50]}»: базовой длины {fmtn(l)} мм нет в ряду ГОСТ 2789-73", pg, bb)
                else:
                    mv = VAL.search(t)
                    if mv and l is not None:
                        v = to_float(mv.group("v"))
                        p = "Ra" if mv.group("p") == "Ra" else "Rz"
                        if v is not None and abs(_default_l(p, v) - l) < 1e-9:
                            once(drw, seen, "R106", t, f"«{t.strip()[:50]}»: базовая длина {fmtn(l)} мм для {mv.group('p')} "
                                 f"{fmtn(v)} принята по умолчанию — её не указывают", pg, bb)
            for m in re.finditer(rf"(?:Ra|Rz|Rmax)\s*({_NUM})\s*(?:…|\.\.\.|–|—)\s*({_NUM})", t):
                a, b = to_float(m.group(1)), to_float(m.group(2))
                if a is not None and b is not None and a > b:
                    once(drw, seen, "R107", m.group(0), f"«{m.group(0)}»: диапазон записывают от меньшего к большему", pg, bb)
            for m in re.finditer(r"±\s*(\d+)\s*%", t):
                if int(m.group(1)) not in (10, 20, 40):
                    once(drw, seen, "R108", m.group(0), f"«{t.strip()[:50]}»: отклонение {m.group(1)} % не из ряда 10, 20, 40 %", pg, bb)


