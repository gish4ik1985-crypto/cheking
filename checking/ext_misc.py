def check_1139(drw: Drawing) -> None:
    seen: set = set()
    for t, pg, bb in texts(drw):
        for m in SPL1139.finditer(t):
            z, d, D = int(m.group("z")), int(m.group("d")), int(m.group("D"))
            if (z, d, D) not in LIGHT | MEDIUM | HEAVY:
                continue
            raw = m.group(0).strip()
            c = m.group("c")
            if not c and re.search(r"1139|(?i:шлиц)", t):
                once(drw, seen, "I901", raw, f"«{raw}»: не указан способ центрирования (D, d или b)", pg, bb)
            if c and c in "ДдвB" and c not in "D":
                once(drw, seen, "I902", raw, f"«{raw}»: буква центрирования «{c}» — нужна латинская D, d или b", pg, bb)
            if any(m.group(k) in ("x", "х") for k in ("s1", "s2", "s3")):
                once(drw, seen, "I903", raw, f"«{raw}»: числа разделяют знаком «×»", pg, bb)
            fits = [m.group(k) for k in ("fd", "fD", "fb") if m.group(k)]
            plain = [f for f in fits if "/" not in f]
            if plain and any(f[0].isupper() for f in plain) and any(f[0].islower() for f in plain):
                once(drw, seen, "I904", raw, f"«{raw}»: в обозначении смешаны поля втулки (прописные) и вала (строчные)", pg, bb)
            for f in fits:
                if "/" in f:
                    a, b_ = f.split("/")
                    if a[0].islower() and b_[0].isupper():
                        once(drw, seen, "I905", raw, f"«{raw}»: в посадке «{f}» поле втулки должно быть в числителе", pg, bb)
            for rx, tab, name in SERIES_WORD:
                if re.search(rx, t, re.I) and (z, d, D) not in tab:
                    once(drw, seen, "I906", raw, f"«{raw}»: сочетание {z}×{d}×{D} не относится к {name} серии ГОСТ 1139-80", pg, bb)


