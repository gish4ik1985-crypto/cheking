def check_taphole(drw: Drawing) -> None:
    from .ext_threads import threads_in_text
    seen: set = set()
    for t, pg, bb in _items(drw):
        if not re.search(r"(?i)под\s+резьб|резьб", t):
            continue
        dm = re.search(r"[⌀Ø∅]\s?(" + _NUM + ")", t)
        if not dm:
            continue
        x = to_float(dm.group(1))
        for th in threads_in_text(t):
            row = TAPHOLE.get(th["d"])
            if not row or x is None:
                continue
            if th["p"] is not None and abs(th["p"] - row[0]) > 1e-9:
                continue                                    # мелкий шаг — другая таблица
            field = re.search(r"\d[GH]|\d[GH]\d[GH]", t)
            g = bool(field and "G" in field.group(0))
            low = row[2] if g else row[1]
            if x < low - 0.005:
                once(drw, seen, "T301", t[:40], f"«{t.strip()[:60]}»: отверстие ⌀{fmtn(x)} меньше наименьшего по табл. 1 "
                     f"ГОСТ 19257-73 для М{fmtn(th['d'])} — {low:.2f} мм", pg, bb)


def check_mfg_ext(drw: Drawing) -> None:
    run_all(drw, (check_forging, check_casting, check_taphole))
