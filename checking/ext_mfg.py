def check_forging(drw: Drawing) -> None:
    blob = _blob(drw)
    if is_forging_drawing(drw):
        for code, rx, what in (("T101", _CLASS, "класса точности (Т1–Т5)"), ("T102", _GROUP, "группы стали (М1–М3)"),
                               ("T103", _CMPLX, "степени сложности (С1–С4)"), ("T104", _INDEX, "исходного индекса (1–23)")):
            if not rx.search(blob):
                emit(drw, code, f"На чертеже поковки нет {what}: по ГОСТ 7505-89 они должны быть указаны на чертеже")
        if "8479" not in blob:
            emit(drw, "T109", "В технических требованиях поковки нет ссылки на ГОСТ 8479 (технические требования к "
                 "поковкам — п. 2.11 ГОСТ 7505-89)")
    seen: set = set()
    limits = ((_CLASS, "класс точности", "Т", range(1, 6), "T1–T5"), (_GROUP, "группа стали", "М", range(1, 4), "М1–М3"),
              (_CMPLX, "степень сложности", "С", range(1, 5), "С1–С4"))
    for t, pg, bb in _items(drw):
        for rx, name, cyr, rng, span in limits:
            for m in rx.finditer(t):
                if m.group("l") in LATIN:
                    once(drw, seen, "T106", (name, t[:40]), f"«{t.strip()[:60]}»: в записи «{name}» буква {m.group('l')} "
                         f"латинская — пишите русскую «{LATIN[m.group('l')]}»", pg, bb)
                n = m.group("n")
                if n and int(n) not in rng:
                    once(drw, seen, "T105", (name, n), f"«{t.strip()[:60]}»: {name} {cyr}{n} — в ГОСТ 7505-89 допустимы "
                         f"{span.replace('T', 'Т')}", pg, bb)
        for m in _INDEX.finditer(t):
            n = m.group("n")
            if n and not 1 <= int(n) <= 23:
                once(drw, seen, "T105", ("индекс", n), f"«{t.strip()[:60]}»: исходный индекс {n} — в ГОСТ 7505-89 "
                     "индексы от 1 до 23", pg, bb)
        if re.search(r"(?i)штамповочн\w*\s+уклон", t):
            vals = [to_float(x) for x in re.findall(rf"({_NUM})\s*°", t)]
            vals = [v for v in vals if v is not None]
            if vals and max(vals) > 12:
                once(drw, seen, "T107", t[:40], f"«{t.strip()[:70]}»: штамповочный уклон {fmtn(max(vals))}° больше "
                     "наибольшего по табл. 18 ГОСТ 7505-89 (10°, в особых случаях 12°)", pg, bb)
            elif vals and max(vals) > 10:
                once(drw, seen, "T107", t[:40], f"«{t.strip()[:70]}»: штамповочный уклон {fmtn(max(vals))}° допустим по "
                     "табл. 18 ГОСТ 7505-89 только на внутренней поверхности рёбер, выступов и реборд (высота/ширина "
                     "больше 2,5); обычный наибольший — 10°", pg, bb)
        if re.search(r"(?i)радиус\w*", t) and re.search(r"(?i)наружн", t):
            vals = [to_float(x) for x in re.findall(rf"(?<![A-Za-zА-Яа-я])[RР]\s?({_NUM})", t)]
            vals = [v for v in vals if v is not None]
            if vals and min(vals) < 1.0:
                once(drw, seen, "T108", t[:40], f"«{t.strip()[:70]}»: радиус наружных углов R{fmtn(min(vals))} меньше "
                     "наименьшего по табл. 7 ГОСТ 7505-89 (1,0 мм)", pg, bb)
        if re.search(r"(?i)ГОСТ\s*7505\s*[-–—]\s*74(?!\d)", t):
            once(drw, seen, "T110", t[:40], f"«{t.strip()[:60]}»: ГОСТ 7505-74 заменён ГОСТ 7505-89", pg, bb)


