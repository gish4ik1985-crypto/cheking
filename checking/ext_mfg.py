_NUM = r"\d+(?:[.,]\d+)?"
_DASH = r"[-–—]"


def _items(drw: Drawing) -> list[tuple[str, int | None, tuple | None]]:
    return [(t, p, b) for t, p, b in texts(drw) if t and t.strip()]


def _blob(drw: Drawing) -> str:
    return " ".join(t for t, _, _ in _items(drw))


def _first(drw: Drawing, rx: re.Pattern):
    """Первая надпись, в которой есть совпадение: (совпадение, страница, bbox)."""
    for t, p, b in _items(drw):
        m = rx.search(t)
        if m:
            return m, p, b, t
    return None


def _name(drw: Drawing) -> str:
    return (drw.title.name or "").lower()


def is_forging_drawing(drw: Drawing) -> bool:
    """Чертёж поковки: в наименовании «Поковка …» / «Штамповка …»."""
    return bool(re.search(r"(?<![а-я])(поковк|штамповк)", _name(drw)))


def is_casting_drawing(drw: Drawing) -> bool:
    return bool(re.search(r"(?<![а-я])отливк", _name(drw)))


