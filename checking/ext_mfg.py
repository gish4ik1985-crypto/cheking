def _cls(raw: str) -> str:
    return re.sub(r"\s", "", raw).lower().replace("t", "т")


def check_casting(drw: Drawing) -> None:
    blob = _blob(drw)
    cast = is_casting_drawing(drw) or "26645" in blob
    seen: set = set()
    acc_found = False
    for t, pg, bb in _items(drw):
        m = _ACC.search(t)
        if m:
            acc_found = True
            body = m.group("body")
            m4 = _ACC4.match(body)
            if not m4:
                once(drw, seen, "T202", t[:40], f"«{t.strip()[:70]}»: в записи точности отливки нужны четыре показателя "
                     "через тире (класс размерной точности, коробление, точность поверхностей, класс массы)", pg, bb)
            else:
                a, b, c, d = _cls(m4.group("a")), int(m4.group("b")), int(m4.group("c")), _cls(m4.group("d"))
                if re.search(r"[tT]", m4.group("a") + m4.group("d")):
                    once(drw, seen, "T207", t[:40], f"«{t.strip()[:70]}»: в классе точности буква «т» должна быть русской", pg, bb)
                for label, val in (("размерной точности", a), ("точности массы", d)):
                    if val != "0" and val not in CASTING_CLASSES:
                        once(drw, seen, "T203", (label, val), f"«{t.strip()[:70]}»: класса {label} «{val}» нет в "
                             "ГОСТ 26645-85 (классы 1…16, у 3, 5, 7, 9, 11, 13 есть вариант с «т»)", pg, bb)
                    if val == "0":
                        once(drw, seen, "T204", label, f"«{t.strip()[:70]}»: класс {label} обязателен (п. 1.5 ГОСТ 26645-85), "
                             "ноль допустим только для ненормируемых показателей", pg, bb)
