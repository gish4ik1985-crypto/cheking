_NON_METAL = {"резина", "полипропилен", "полиэтилен", "полиамид", "фторопласт"}
_STEEL, _STAINLESS, _ALU = "t_steel", "t_stainless", "t_alu"
_MAT_KEY = {"сталь": _STEEL, "нерж. сталь": _STAINLESS, "алюминиевый сплав": _ALU}
_MAT_RU = {_STEEL: "сталь", _STAINLESS: "нержавеющая сталь", _ALU: "алюминий"}


def _material_key(drw: Drawing) -> str | None:
    text = " ".join(x for x in (drw.title.material, (drw.facts.get("material") or {}).get("raw")) if x)
    d = density_for(text)
    return _MAT_KEY.get(d[1]) if d else None


def _blob(drw: Drawing) -> str:
    return " ".join(t for t, _, _ in texts(drw) if t)


def _sheet(drw: Drawing, prof: Profile) -> None:
    from .rules import _overall
    s = drw.facts.get("sheet_thickness")
    lasers = prof.of("laser_sheet")
    if not s or not lasers or drw.facts.get("is_assembly"):
        return
    # T401: габарит листа
    ov = drw.facts.get("overall") or _overall(drw)
    L = ov.get("L")
    beds = [(i, i["params"]["bed_l"], i["params"]["bed_w"]) for i in lasers
            if (i.get("params") or {}).get("bed_l") and (i.get("params") or {}).get("bed_w")]
    if L and beds and not drw.ocr and len(beds) == len(lasers):
        big = max(beds, key=lambda b: max(b[1], b[2]))
        if L > max(big[1], big[2]):
            emit(drw, "T401", f"Наибольший размер ≈ {fmtn(L)} мм больше рабочего поля лазерных станков предприятия "
                 f"({fmtn(big[1])}×{fmtn(big[2])} мм, {label(big[0])})")
    # T402: толщина
    key = _material_key(drw)
    if key:
        top, who, unknown = prof.best(("laser_sheet",), key)
        if top is not None and not unknown and s > top:
            emit(drw, "T402", f"Лист {fmtn(s)} мм ({_MAT_RU[key]}) толще предельной для лазерной резки на предприятии "
                 f"({fmtn(top)} мм, {label(who)}): нужна плазменная, газокислородная резка или кооперация")


def _turning(drw: Drawing, prof: Profile) -> None:
    from .rules import _overall
    if drw.facts.get("sheet_thickness") or drw.facts.get("is_assembly") or drw.ocr:
        return
    mat = density_for(" ".join(x for x in (drw.title.material, (drw.facts.get("material") or {}).get("raw")) if x))
    if mat and mat[1] in _NON_METAL:                           # резина, пластик — не точение на токарном станке по металлу
        return
    ov = drw.facts.get("overall") or _overall(drw)
    D = ov.get("D")
    if not D:
        return
    top, who, unknown = prof.best(("lathe", "lathe_cnc", "lathe_carousel"), "swing")
    if top is not None and not unknown and D > top:
        emit(drw, "T403", f"Диаметр ⌀{fmtn(D)} мм больше наибольшего диаметра обработки токарных станков предприятия "
             f"({fmtn(top)} мм, {label(who)})")


def _num(v) -> float | None:
    r = re.search(r"\d+(?:[.,]\d+)?", str(v or ""))
    return to_float(r.group(0)) if r else None


def _gears(drw: Drawing, prof: Profile) -> None:
    gears = drw.facts.get("gear") or []
    if not gears:
        return
    machines = prof.of("gear_hob", "gear_shaper")
    for g in gears:
        if g.get("spline"):
            continue
        m, z, d = (_num(g.get(k)) for k in ("m", "z", "d"))
        if not d and m and z:
            b = re.search(r"(\d+)\s*°", str(g.get("beta") or ""))
            d = m * z / (math.cos(math.radians(float(b.group(1)))) if b else 1)
        if not d:
            continue
        if not machines:
            emit(drw, "T404", "На чертеже зубчатое колесо, а зубообрабатывающих станков (зубофрезерных, зубодолбёжных) в "
                 "профиле предприятия нет")
            return
        top, who, unknown = prof.best(("gear_hob", "gear_shaper"), "gear_d")
        if top is not None and not unknown and d > top:
            emit(drw, "T404", f"Колесо{f' m={fmtn(m)}' if m else ''}{f', z={int(z)}' if z else ''}: d = {fmtn(round(d, 1))} мм "
                 f"больше наибольшего диаметра колёс на зубообрабатывающих станках предприятия ({fmtn(top)} мм, {label(who)})")


_HEAT = re.compile(r"(?i)закал|цементир|азотир|нормализ|улучшени|улучшить|отпуск")
_TVCH = re.compile(r"(?i)\bТВЧ\b|токами\s+высокой")
_PLATING = re.compile(r"(?<![А-Яа-яA-Za-z])(?:Ц\d{1,2}(?:\.[а-я.]+)?|Хим\.?\s*Окс|Ан\.?\s*Окс|Хим\.?\s*Фос|Хр\d{1,2})"
                      r"(?![А-Яа-яA-Za-z])")
_PLATING_WORD = re.compile(r"(?i)гальванич|цинков|хромир|никелир|оксидир|анодир")


def _processes(drw: Drawing, prof: Profile) -> None:
    blob = _blob(drw)
    if not blob:
        return
    if _HEAT.search(blob) and not prof.has("furnace"):
        emit(drw, "T406", "В ТТ названа термообработка (закалка, отпуск, цементация, азотирование и т. п.), а электропечей в "
             "профиле предприятия нет")
    if _TVCH.search(blob) and not prof.has("induction"):
        emit(drw, "T406", "В ТТ названа закалка ТВЧ, а генератора ТВЧ в профиле предприятия нет")
    if re.search(r"(?i)электроэрозион|проволочно-вырез", blob) and not prof.has("edm_wire"):
        emit(drw, "T407", "В тексте чертежа названа электроэрозионная обработка, а электроэрозионных станков в профиле нет")
    if re.search(r"(?i)лазерн\w+\s+сварк", blob) and not prof.has("laser_weld"):
        emit(drw, "T407", "В тексте чертежа названа лазерная сварка, а установки лазерной сварки в профиле нет")
    if re.search(r"(?i)зубошлифован", blob) and not prof.has("gear_grind"):
        emit(drw, "T407", "В тексте чертежа названо зубошлифование, а зубошлифовальных станков в профиле нет")
    found = _PLATING.search(" ".join(drw.tt or [])) or _PLATING_WORD.search(blob)
    if found and not prof.has("plating"):
        emit(drw, "T408", f"Покрытие «{found.group(0)}»: гальванического оборудования в профиле "
             "предприятия нет — операция выполняется кооперацией")


def _precision(drw: Drawing, prof: Profile) -> None:
    if prof.has("lapping"):
        return
    tight = [d for d in drw.dims if d.upper is not None and d.lower is not None and not d.reference and d.nominal
             and 0 < d.upper - d.lower <= 0.004 + 1e-9]
    fine = [r for r in drw.roughness if r.get("param") == "Ra" and r.get("value") is not None and r["value"] <= 0.1]
    if tight or fine:
        parts = []
        if tight:
            parts.append(f"размер {tight[0].raw} (допуск {fmtn(round((tight[0].upper - tight[0].lower) * 1000, 1))} мкм)")
        if fine:
            parts.append(f"Ra {fmtn(fine[0]['value'])}")
        emit(drw, "T405", f"{' и '.join(parts)} {'требуют' if len(parts) > 1 else 'требует'} доводки (притирка, хонингование, суперфиниш), а такого оборудования в "
             "профиле предприятия нет — обычно кооперация")


def check_equip_ext(drw: Drawing, cfg: dict) -> None:
    prof = Profile(cfg)
    if not prof.items or drw.facts.get("is_assembly"):
        return
    if not (drw.title.found or drw.title.designation):        # не конструкторский документ (паспорт, инструкция, прайс)
        return
    for fn in (_sheet, _turning, _gears, _processes, _precision):
        fn(drw, prof)


