def check_23360(drw: Drawing) -> None:
    seen: set = set()
    slot_fields: dict[float, set] = {}
    slot_dims = []
    for d in drw.dims:
        if d.kind != "linear" or not d.nominal:
            continue
        f = (d.field or "").upper().replace("JS", "JS")
        if f in SLOT_FIELDS and d.nominal not in KEY_WIDTHS and f in ("N9", "JS9", "P9"):
            once(drw, seen, "I601", d.nominal, f"Паз «{d.raw}»: ширины шпонки {fmtn(d.nominal)} мм нет в ГОСТ 23360-78 "
                 f"({', '.join(str(x) for x in KEY_WIDTHS[:10])}…)", d.page, d.bbox)
        if f in SLOT_FIELDS and d.nominal in KEY_WIDTHS:
            slot_fields.setdefault(d.nominal, set()).add(f)
            slot_dims.append(d)
        elif f and d.nominal in KEY_WIDTHS and re.fullmatch(r"[A-Z]{1,2}\d{1,2}", f) and f not in SLOT_FIELDS:
            g = int(re.sub(r"\D", "", f))
            if g >= 7 and f[0] in "HNPJD":
                once(drw, seen, "I602", (d.nominal, f), f"«{d.raw}»: поле {f} ширины паза не из ГОСТ 23360-78 "
                     f"(H9, N9, P9 — вал; D10, Js9, P9 — втулка)", d.page, d.bbox)
    for b, fs in slot_fields.items():
        if len(fs) >= 2:
            kinds = {k for k, (a, c) in SLOT_PAIRS.items() if a in fs or c in fs}
            if len(kinds) > 1:
                once(drw, seen, "I603", b, f"Паз шириной {fmtn(b)} мм: поля {', '.join(sorted(fs))} — из разных видов "
                     f"соединения (свободное H9/D10, нормальное N9/Js9, плотное P9/P9)")
    for t, pg, bb in texts(drw):
        if not re.search(r"[Шш]понк", t):
            continue
        for m in KEY_DES.finditer(t):
            b, h, l = int(m.group("b")), int(m.group("h")), int(m.group("l"))
            raw = m.group(0).strip()
            ex = m.group("ex")
            if (b, h) not in KEY_BH:
                once(drw, seen, "I604", raw, f"«{raw}»: сечения {b}×{h} в ГОСТ 23360-78 нет"
                     + (f" (для b = {b} h = {', '.join(str(hh) for bb_, hh in sorted(KEY_BH) if bb_ == b)})"
                        if any(bb_ == b for bb_, _ in KEY_BH) else ""), pg, bb)
            if l not in KEY_LENGTHS and l <= 500:
                once(drw, seen, "I605", raw, f"«{raw}»: длины {l} мм нет в ряду шпонок ГОСТ 23360-78", pg, bb)
            rng = KEY_L_RANGE.get((b, h))
            if rng and l in KEY_LENGTHS and not rng[0] <= l <= rng[1]:
                once(drw, seen, "I606", raw, f"«{raw}»: для сечения {b}×{h} длина шпонки {rng[0]}–{rng[1]} мм", pg, bb)
            if not re.search(r"ГОСТ|ОСТ|СТ\s?СЭВ", t):
                once(drw, seen, "I607", raw, f"«{raw}»: нет обозначения стандарта — «Шпонка {raw} ГОСТ 23360-78»", pg, bb)
            if ex and ex not in ("2", "3"):
                once(drw, seen, "I608", raw, f"«{raw}»: исполнение «{ex}-» — у призматических шпонок исполнения 2 и 3 "
                     f"указывают префиксом, исполнение 1 не обозначают", pg, bb)
    if slot_dims:
        from . import views
        try:
            frames = views.collect(drw)["frames"]
        except Exception:
            frames = []
        syms = {f["sym"] for f in frames}
        if "∥" not in syms or "⌯" not in syms:
            d = slot_dims[0]
            once(drw, seen, "I609", "slot", f"Паз «{d.raw}»: не найдены допуски "
                 f"{'параллельности' if '∥' not in syms else ''}{' и ' if '∥' not in syms and '⌯' not in syms else ''}"
                 f"{'симметричности' if '⌯' not in syms else ''} пазов (рекомендуются приложением к ГОСТ 23360-78)",
                 d.page, d.bbox)
    name = (getattr(drw.title, "name", "") or "").lower()
    if "шпонк" in name:
        for d in drw.dims:
            if d.kind != "linear" or not d.nominal or not d.field:
                continue
            f = d.field
            if d.nominal in KEY_WIDTHS and f != "h9":
                once(drw, seen, "I610", ("b", d.raw), f"«{d.raw}»: ширина шпонки b — поле h9 (ГОСТ 23360-78)", d.page, d.bbox)
        # длина l — h14 и высота h — h9/h11
        for d in drw.dims:
            if d.kind == "linear" and d.nominal in KEY_LENGTHS and d.nominal > 20 and d.field and d.field != "h14":
                once(drw, seen, "I610", ("l", d.raw), f"«{d.raw}»: длина шпонки l — поле h14 (ГОСТ 23360-78)", d.page, d.bbox)
    diams = [d.nominal for d in drw.dims if d.kind == "diameter" and d.nominal and not d.reference]
    for b in slot_fields:
        for row in KEYS_23360:
            if row[2] != b:
                continue
            for dd in diams:
                if not row[0] < dd <= row[1]:
                    continue
                exp = {round(dd - row[4], 2), round(dd + row[5], 2)}
                near = [x for x in drw.dims if x.kind == "linear" and x.nominal and not x.field
                        and any(0.1 <= abs(x.nominal - e) <= 0.6 for e in exp)]
                if near and not any(abs(x.nominal - e) < 0.06 for x in drw.dims if x.kind == "linear" and x.nominal for e in exp):
                    x = near[0]
                    once(drw, seen, "I611", (b, dd), f"Паз шириной {fmtn(b)} мм на валу ⌀{fmtn(dd)}: по ГОСТ 23360-78 "
                         f"d−t1 = {fmtn(round(dd - row[4], 2))}, d+t2 = {fmtn(round(dd + row[5], 2))}; на чертеже "
                         f"«{x.raw}» — проверьте глубину паза", x.page, x.bbox)


