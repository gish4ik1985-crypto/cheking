def check_spline_table(drw: Drawing) -> None:
    seen: set = set()
    for t in parse_tables(drw):
        if not t["spline"]:
            continue
        p, pg = t["params"], t["page"]
        m, z, x = _num(p.get("m")), _num(p.get("z")), _num(p.get("x"))
        rows = {}
        for key, rx in RX_SPL.items():
            for r in t["rows"]:
                if rx.search(re.sub(r"\s+", " ", r["label"]).strip()):
                    rows[key] = r
                    break
        num = lambda r: (to_float(re.search(r"[-+]?\d+(?:[.,]\d+)?", r["value"]).group(0)) if r and re.search(r"\d", r["value"]) else None)  # noqa: E731
        D, db, al = num(rows.get("D")), num(rows.get("db")), num(rows.get("alpha"))
        where = (pg, t["bbox"])
        if m and z and D is not None:
            exp = m * z + 2 * (x or 0.0) * m + 1.1 * m
            if abs(D - exp) > 0.05:
                once(drw, seen, "I511", pg, f"Номинальный диаметр D = {fmtn(D)}, а m·z + 2·x·m + 1,1·m = {fmtn(round(exp, 3))}", *where)
        if m and z and db is not None:
            exp = m * z * math.cos(math.radians(30))
            if abs(db - exp) > 0.05:
                once(drw, seen, "I512", pg, f"Диаметр основной окружности db = {fmtn(db)}, а m·z·cos 30° = {fmtn(round(exp, 3))}", *where)
        if al is not None and abs(al - 30) > 1e-6:
            once(drw, seen, "I513", pg, f"Угол профиля {fmtn(al)}° — у шлицев по ГОСТ 6033-80 он равен 30°", *where)


