def check_angles(drw: Drawing) -> None:
    seen: set = set()
    first = {0, 5, 10, 15, 20, 30, 45, 60, 75, 90, 120}
    for d in drw.dims:
        if d.kind != "angle" or d.nominal is None:
            continue
        deg = d.nominal
        raw = d.raw
        if deg > 360 or deg < 0:
            once(drw, seen, "U202", raw, f"Угол «{raw}»: значение вне 0…360°", d.page, d.bbox)
        if re.search(r"\d[.,]\d+\s*°", raw) and d.nominal % 1:
            once(drw, seen, "U203", raw, f"Угол «{raw}»: дробную часть градуса записывают минутами", d.page, d.bbox)
        if re.search(r"мин|сек|''", raw):
            once(drw, seen, "U204", raw, f"Угол «{raw}»: минуты и секунды обозначают знаками ′ и ″", d.page, d.bbox)
        if deg not in first and abs(deg - round(deg)) < 1e-9 and 0 < deg < 360 and "′" not in raw and "'" not in raw:
            once(drw, seen, "U201", raw, f"Угол «{raw}» — не из 1-го ряда ГОСТ 8908-81", d.page, d.bbox)
    cone = {3, 5, 6, 7, 8, 10, 12, 15, 20, 30, 50, 100, 200}
    for t, pg, bb in texts(drw):
        m = re.search(r"(?i)конусност\w*\s*(?:C\s*=\s*)?1\s*:\s*(\d+(?:[.,]\d+)?)", t)
        if m:
            n = to_float(m.group(1))
            if n not in cone and not re.search(r"морзе|метрическ|ГОСТ\s*2848|ГОСТ\s*25557", t, re.I):
                once(drw, seen, "U205", m.group(0), f"«{m.group(0)}»: конусность 1:{m.group(1)} не из ряда нормальных "
                     f"конусностей ГОСТ 8593-81", pg, bb)
        if re.search(r"(?i)\bуклон\w*\s*\d+(?:[.,]\d+)?\s*°", t) and not re.search(r"1\s*:\s*\d|%", t):
            once(drw, seen, "U206", t[:40], f"«{t.strip()[:50]}»: уклон задают отношением («1:10») или в процентах", pg, bb)


