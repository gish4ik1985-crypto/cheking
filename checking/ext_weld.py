def check_14771(drw: Drawing) -> None:
    seen: set = set()
    tt = " ".join(t for t, _, _ in texts(drw))
    welds = [w for w in _welds(drw) if _is14771(w, tt)]
    if not welds:
        return
    thick = [d.nominal for d in drw.dims if d.kind == "thickness" and d.nominal]
    if drw.facts.get("sheet_thickness"):
        thick.append(drw.facts["sheet_thickness"])
    methods = {w["method14771"] for w in welds if w["method14771"]}
    for w in welds:
        key = (w["type"], w["num"])
        me = w["method14771"]
        pg, bb, raw = w["page"], w["bbox"], w["text"]
        if me and key in ALLOWED and me not in ALLOWED[key]:
            once(drw, seen, "Y101", (raw, me), f"«{raw}»: соединение {key[0]}{key[1]} в ГОСТ 14771-76 выполняют способами "
                 f"{', '.join(sorted(ALLOWED[key]))}; «{me}» не предусмотрен", pg, bb)
        legm = re.search(r"[⊿△▷]", raw)
        mm = METHOD_RX.search(raw)
        if legm and mm and legm.start() < mm.start():
            once(drw, seen, "Y106", raw, f"«{raw}»: способ сварки пишут перед катетом — «{key[0]}{key[1]}-{me}-⊿…»", pg, bb)
        rng = THICK.get(key, {}).get(me) if me else None
        if rng and thick:
            lo, hi = min(thick), max(thick)
            if hi < rng[0] or lo > rng[1]:
                code = {"С": "Y102", "У": "Y103", "Т": "Y104", "Н": "Y105"}[w["type"]]
                once(drw, seen, code, (raw, lo, hi), f"«{raw}»: по ГОСТ 14771-76 соединение {key[0]}{key[1]} способом {me} "
                     f"выполняют при s = {fmtn(rng[0])}–{fmtn(rng[1])} мм, а на чертеже {fmtn(lo)}"
                     f"{'' if lo == hi else '–' + fmtn(hi)} мм", pg, bb)
        if key == ("С", 4) and not re.search(r"подкладк", tt, re.I):
            once(drw, seen, "Y110", raw, f"«{raw}»: соединение на остающейся подкладке — материал подкладки не указан", pg, bb)
    for rx, ok_methods in WORD_METHOD:
        m = re.search(rx, tt, re.I)
        if m and methods and not (methods & ok_methods):
            once(drw, seen, "Y107", rx, f"В ТТ «{m.group(0)}», а в обозначениях швов способы {', '.join(sorted(methods))} — не "
                 f"согласуются (для этого слова ожидаются {', '.join(sorted(ok_methods))})")
    if not re.search(r"проволок|электрод|Св-?\d|Св\.|защитн\w+\s+газ|аргон|углекисл|CO2|СО2", tt, re.I):
        once(drw, seen, "Y108", "x", "В ТТ нет сварочных материалов (проволока, электроды, защитный газ)")
    if not re.search(r"контрол|проверк|дефектоскоп|осмотр|герметичн", tt, re.I):
        once(drw, seen, "Y109", "x", "В ТТ нет требования о контроле сварных швов")
    if re.search(r"закрыт|замкнут|короб|глух", tt, re.I) and any(k in {("С", 6), ("У", 5), ("Т", 3), ("Н", 2)}
                                                                 for k in ((w["type"], w["num"]) for w in welds)):
        once(drw, seen, "Y111", "x", "Двусторонние швы и слова о закрытом объёме — проверьте доступ к обратной стороне шва")


def check_weld_ext(drw: Drawing) -> None:
    run_all(drw, (check_14771,))
