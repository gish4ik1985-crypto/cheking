def _welds(drw: Drawing) -> list[dict]:
    out = []
    for ln in drw.lines:
        if len(ln.text) > 45:
            continue
        w = _parse(ln.text)
        if not w:
            continue
        m = METHOD_RX.search(ln.text)
        w["method14771"] = m.group(1) if m else None
        w["page"], w["bbox"], w["text"] = ln.page, ln.bbox, ln.text.strip()
        out.append(w)
    return out


def _is14771(w: dict, tt: str) -> bool:
    return w["std"] == "14771" or (not w["std"] and re.search(r"14771", tt) is not None and not re.search(r"5264|8713", tt))


