def _legacy(cfg: dict, path: tuple) -> bool | None:
    v = cfg
    for k in path:
        if not isinstance(v, dict) or k not in v:
            return None
        v = v[k]
    return bool(v) if isinstance(v, bool) else None


def custom_meta(cfg: dict) -> list[tuple]:
    """Правила предприятия из config.json в формате RULES."""
    return [(r["code"], "custom", r.get("title", r["code"]), True, r.get("severity", "warning"))
            for r in cfg.get("custom_rules") or [] if r.get("code")]


def all_rules(cfg: dict) -> list[tuple]:
    return RULES + custom_meta(cfg)


def rule_settings(cfg: dict, code: str, _meta: dict | None = None) -> tuple[bool, str | None]:
    """(включено, принудительная важность или None)."""
    meta = RULE_INDEX.get(code) or (_meta or {r[0]: r for r in custom_meta(cfg)}).get(code)
    if meta and meta[1] in LOCKED_GROUPS:
        return True, None
    ov = (cfg.get("rules") or {}).get(code) or {}
    sev = ov.get("severity") if ov.get("severity") in (ERROR, WARNING, INFO) else None
    if "enabled" in ov:
        return bool(ov["enabled"]), sev
    if code in LEGACY_SWITCHES:
        lv = _legacy(cfg, LEGACY_SWITCHES[code])
        if lv is not None:
            return lv, sev
    return (meta[3] if meta else True), sev


def profile(cfg: dict) -> dict[str, tuple[bool, str | None]]:
    cm = {r[0]: r for r in custom_meta(cfg)}
    return {r[0]: rule_settings(cfg, r[0], cm) for r in RULES + list(cm.values())}


def _sort_key(sev: str, cat: str):
    return SEVERITY_ORDER[sev], CATEGORY_ORDER.index(cat) if cat in CATEGORY_ORDER else 99


def apply_to_dict(d: dict, cfg: dict) -> dict:
    """Убирает выключенные правила и подменяет важность (на копии словаря чертежа)."""
    prof = profile(cfg)
    out = dict(d)
    keep = []
    for f in d.get("findings", []):
        on, sev = prof.get(f["code"], (True, None))
        if not on:
            continue
        if sev and sev != f["severity"]:
            f = {**f, "severity": sev, "severity_ru": {ERROR: "Ошибка", WARNING: "Предупреждение",
                                                       INFO: "Замечание"}[sev]}
        keep.append(f)
    keep.sort(key=lambda f: _sort_key(f["severity"], f.get("category", "")))
    out["findings"] = keep
    out["suppressed"] = [f for f in d.get("suppressed", []) if prof.get(f["code"], (True, None))[0]]
    out["counts"] = {s: sum(1 for f in keep if f["severity"] == s) for s in (ERROR, WARNING, INFO)}
    return out


def apply_to_drawing(drw, cfg: dict) -> None:
    prof = profile(cfg)
    keep = []
    for f in drw.findings:
        on, sev = prof.get(f.code, (True, None))
        if not on:
            continue
        if sev:
            f.severity = sev
        keep.append(f)
    keep.sort(key=lambda f: _sort_key(f.severity, f.category))
    drw.findings = keep


def catalog_view(cfg: dict) -> list[dict]:
    """Группы с правилами и их текущим состоянием — для панели администратора."""
    out = []
    cm = custom_meta(cfg)
    for key, title, stds, descr in GROUPS:
        rules = []
        for code, grp, text, default, typ in RULES + cm:
            if grp != key:
                continue
            on, sev = rule_settings(cfg, code)
            rules.append({"code": code, "text": text, "enabled": on, "default": default, "severity": sev,
                          "typical": typ})
        out.append({"key": key, "title": title, "standards": stds, "description": descr,
                    "locked": key in LOCKED_GROUPS, "rules": rules})
    return out
