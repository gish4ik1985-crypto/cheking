def _legacy(cfg: dict, path: tuple) -> bool | None:
    v = cfg
    for k in path:
        if not isinstance(v, dict) or k not in v:
            return None
        v = v[k]
    return bool(v) if isinstance(v, bool) else None


def custom_meta(cfg: dict) -> list[tuple]:
    """Правила предприятия из config.json в формате RULES."""
    return [(r["code"], "custom", r.get("title", r["code"]), True, r.get("severity", "warning"))
            for r in cfg.get("custom_rules") or [] if r.get("code")]


def all_rules(cfg: dict) -> list[tuple]:
    return RULES + custom_meta(cfg)


def module_enabled(cfg: dict, key: str) -> bool:
    v = (cfg.get("modules") or {}).get(key)
    return bool(v) if isinstance(v, bool) else MODULES[key]["default"]


def rule_settings(cfg: dict, code: str, _meta: dict | None = None, gated: bool = True) -> tuple[bool, str | None]:
    """(включено, принудительная важность или None). gated=False — собственная настройка правила, без учёта
    выключенного блока (так её показывает панель администратора)."""
    meta = RULE_INDEX.get(code) or (_meta or {r[0]: r for r in custom_meta(cfg)}).get(code)
    if meta and meta[1] in LOCKED_GROUPS:
        return True, None
    if gated and meta and meta[1] in GROUP_MODULE and not module_enabled(cfg, GROUP_MODULE[meta[1]]):
        return False, None
    ov = (cfg.get("rules") or {}).get(code) or {}
    sev = ov.get("severity") if ov.get("severity") in (ERROR, WARNING, INFO) else None
    if "enabled" in ov:
        return bool(ov["enabled"]), sev
    if code in LEGACY_SWITCHES:
        lv = _legacy(cfg, LEGACY_SWITCHES[code])
        if lv is not None:
            return lv, sev
    return (meta[3] if meta else True), sev


def profile(cfg: dict) -> dict[str, tuple[bool, str | None]]:
    cm = {r[0]: r for r in custom_meta(cfg)}
    return {r[0]: rule_settings(cfg, r[0], cm) for r in RULES + list(cm.values())}


def _sort_key(sev: str, cat: str):
    return SEVERITY_ORDER[sev], CATEGORY_ORDER.index(cat) if cat in CATEGORY_ORDER else 99


def apply_to_dict(d: dict, cfg: dict) -> dict:
    """Убирает выключенные правила и подменяет важность (на копии словаря чертежа)."""
    prof = profile(cfg)
    out = dict(d)
    keep = []
    for f in d.get("findings", []):
        on, sev = prof.get(f["code"], (True, None))
        if not on:
            continue
        if sev and sev != f["severity"]:
            f = {**f, "severity": sev, "severity_ru": {ERROR: "Ошибка", WARNING: "Предупреждение",
                                                       INFO: "Замечание"}[sev]}
        keep.append(f)
    keep.sort(key=lambda f: _sort_key(f["severity"], f.get("category", "")))
    out["findings"] = keep
    out["suppressed"] = [f for f in d.get("suppressed", []) if prof.get(f["code"], (True, None))[0]]
    out["counts"] = {s: sum(1 for f in keep if f["severity"] == s) for s in (ERROR, WARNING, INFO)}
    return out


def apply_to_drawing(drw, cfg: dict) -> None:
    prof = profile(cfg)
    keep = []
    for f in drw.findings:
        on, sev = prof.get(f.code, (True, None))
        if not on:
            continue
        if sev:
            f.severity = sev
        keep.append(f)
    keep.sort(key=lambda f: _sort_key(f.severity, f.category))
    drw.findings = keep


def catalog_view(cfg: dict) -> list[dict]:
    """Группы с правилами и их текущим состоянием — для панели администратора."""
    out = []
    cm = custom_meta(cfg)
    for key, title, stds, descr in GROUPS:
        rules = []
        for code, grp, text, default, typ in RULES + cm:
            if grp != key:
                continue
            on, sev = rule_settings(cfg, code, gated=False)
            rules.append({"code": code, "text": text, "enabled": on, "default": default, "severity": sev,
                          "typical": typ, "doc": RULE_DOCS.get(code) or custom_doc(cfg, code), "rev": rev_of(code)})
        out.append({"key": key, "title": title, "standards": stds, "description": descr,
                    "locked": key in LOCKED_GROUPS, "rules": rules, "clauses": CLAUSES.get(key, []),
                    "section": next((s for s, _, gs in SECTIONS if key in gs), "own")})
    return out


def sections_view(cfg: dict) -> list[dict]:
    return [{"key": k, "title": t, "module": ({"enabled": module_enabled(cfg, k), "default": MODULES[k]["default"],
                                                "descr": MODULES[k]["descr"]} if k in MODULES else None)}
            for k, t, _ in SECTIONS]


# --- Индекс «стандарт → проверки» -----------------------------------------------------------------
_STD_TOKEN = re.compile(r"(?P<gost>ГОСТ\s*(?P<r>Р\s*)?(?P<num>\d[\d.]*)\s*[-–]\s*(?P<yr>\d{2,4}))"
                        r"|(?P<ost>ОСТ\s*4\s*Г[О0]\.070\.(?P<on>\d{3}))")
_CLAUSE = re.compile(r"(?:п\.|пп\.|разд\.|раздел)\s*[\d.]+(?:\s*[-–]\s*[\d.]+)?|\(область применения\)")


def _year(y: str) -> int:
    n = int(y)
    return n if n > 99 else (1900 + n if n >= 40 else 2000 + n)


def parse_standards(text: str) -> list[tuple[str, str, str, int]]:
    """«ГОСТ 2.109-73 п. 3.2.1» → [(ключ, название, пункт, год)]. Ключ без года: «ГОСТ 2.109»."""
    out = []
    ms = list(_STD_TOKEN.finditer(text or ""))
    for i, m in enumerate(ms):
        tail = text[m.end(): ms[i + 1].start() if i + 1 < len(ms) else len(text)]
        cm = _CLAUSE.search(tail)
        clause = cm.group(0).strip("() ") if cm else ""
        if m.group("gost"):
            r = "Р " if m.group("r") else ""
            out.append((f"ГОСТ {r}{m.group('num')}", f"ГОСТ {r}{m.group('num')}-{m.group('yr')}", clause, _year(m.group("yr"))))
        else:
            n = m.group("on")
            out.append((f"ОСТ4 ГО.070.{n}", f"ОСТ4 ГО.070.{n}", clause, 0))
    return out


def _std_sort(key: str):
    kind = 1 if key.startswith("ГОСТ Р") else 0 if key.startswith("ГОСТ") else 2
    nums = tuple(int(x) for x in re.findall(r"\d+", key))
    return kind, nums


def standards_index(cfg: dict) -> list[dict]:
    """Для каждого стандарта: проверки, которые на него ссылаются (direct, с пунктом), и остальные проверки тех
    групп, где он назван (related). Состояние проверок берётся из группы на клиенте."""
    idx: dict[str, dict] = {}

    def entry(key, label, year):
        e = idx.setdefault(key, {"key": key, "label": label, "year": year, "direct": {}, "related": [], "groups": []})
        if year > e["year"]:
            e["label"], e["year"] = label, year
        return e

    cm = custom_meta(cfg)
    refs = {r["code"]: r.get("ref") for r in cfg.get("custom_rules") or [] if r.get("code")}
    group_of = {r[0]: r[1] for r in RULES + cm}
    direct_codes: set[str] = set()
    for code in group_of:
        texts = list(RULE_STANDARDS.get(code, []))
        if code in EXT_REG:
            texts.append(EXT_REG[code]["std"])
        if refs.get(code):
            texts.append(refs[code])
        for t in texts:
            for key, label, clause, yr in parse_standards(t):
                e = entry(key, label, yr)
                e["direct"].setdefault(code, [])
                if clause and clause not in e["direct"][code]:
                    e["direct"][code].append(clause)
                direct_codes.add(code)
    for gkey, _, stds, _d in GROUPS:
        for key, label, _c, yr in parse_standards(stds):
            e = entry(key, label, yr)
            if gkey not in e["groups"]:
                e["groups"].append(gkey)
            for code, g in group_of.items():
                if g == gkey and code not in e["direct"] and code not in e["related"]:
                    e["related"].append(code)
    out = []
    for key in sorted(idx, key=_std_sort):
        e = idx[key]
        out.append({"key": key, "label": e["label"], "groups": e["groups"],
                    "direct": [{"code": c, "clauses": cl} for c, cl in e["direct"].items()],
                    "related": e["related"]})
    return out


def custom_doc(cfg: dict, code: str) -> dict | None:
    """Описание правила предприятия — из его настроек (checking/custom.describe)."""
    from . import custom
    r = next((x for x in cfg.get("custom_rules") or [] if x.get("code") == code), None)
    return custom.describe(r) if r else None
