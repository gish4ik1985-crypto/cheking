def clearance_for(d: float) -> int | None:
    """Резьба, под которую ⌀d — стандартное сквозное отверстие (ГОСТ 11284), или None."""
    for i in range(3):                      # сначала 1-й ряд, затем 2-й и 3-й: ⌀17 — 1-й ряд М16 (и 3-й ряд М14)
        for m, row in CLEARANCE_HOLES.items():
            if abs(d - row[i]) < 1e-6:
                return m
    return None


