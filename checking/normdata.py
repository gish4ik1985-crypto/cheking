def scale_ok(sc: str) -> bool:
    """Масштаб из ряда ГОСТ 2.302-68 или (100·n):1 (п. 4, n — целое)."""
    if sc in SCALES:
        return True
    m = re.fullmatch(r"(\d+):1", sc)
    return bool(m and int(m.group(1)) >= 100 and int(m.group(1)) % 100 == 0)


