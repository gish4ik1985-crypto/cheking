def density_for(material: str) -> tuple[float, str] | None:
    if not material:
        return None
    for pat, rho, name in DENSITIES:
        if re.search(pat, material, re.I):
            return rho, name
    return None


def fmtn(v: float | None) -> str:
    if v is None:
        return "—"
    s = f"{v:.4f}".rstrip("0").rstrip(".")
    return s.replace(".", ",")
