def check_metric_thread(d: float, pitch: float | None) -> tuple[bool, str]:
    """(ok, сообщение). pitch=None — резьба с крупным шагом."""
    entry = METRIC_THREADS.get(d)
    if entry is None:
        near = sorted(METRIC_THREADS, key=lambda x: abs(x - d))[:2]
        return False, (f"Диаметра М{fmtn(d)} нет в ряду ГОСТ 8724-2002; ближайшие: "
                       + ", ".join(f"М{fmtn(x)}" for x in near))
    coarse, fine = entry
    if pitch is None:
        if coarse is None:
            return False, (f"Для М{fmtn(d)} крупный шаг не установлен — нужно указать мелкий шаг "
                           f"({', '.join(fmtn(p) for p in fine)})")
        return True, ""
    if coarse is not None and abs(pitch - coarse) < 1e-6:
        return True, "крупный шаг указан явно (по ГОСТ 8724 крупный шаг не указывают)"
    if any(abs(pitch - p) < 1e-6 for p in fine):
        return True, ""
    allowed = ([fmtn(coarse)] if coarse else []) + [fmtn(p) for p in fine]
    return False, f"Шаг {fmtn(pitch)} не предусмотрен для М{fmtn(d)}; допустимо: {', '.join(allowed)}"


