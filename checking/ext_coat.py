def check_9306(drw: Drawing) -> None:
    seen: set = set()
    for comps, raw, pg, bb in _designations(drw):
        toks = [c for c in comps if c != "/"]
        lat_word = bool(re.search(r"[A-Za-z]", raw))
        for c in toks:
            m = TOKEN.fullmatch(c)
            if not m or not m.group(2) or lat_word:
                continue
            w = m.group(1)
            if w not in METAL and not w.upper().startswith("ПОС"):
                once(drw, seen, "H101", c, f"«{raw}»: «{w}» — нет такого символа материала покрытия (таблицы 3, 4 ГОСТ 9.306-85)", pg, bb)
            v = to_float(m.group(2))
            if v is not None and v <= 1 and w not in PRECIOUS and w in METAL:
                once(drw, seen, "H105", c, f"«{raw}»: толщину {m.group(2)} мкм (1 мкм и менее) в обозначении не указывают", pg, bb)
        if re.search(r"\d\s*мк", raw):
            once(drw, seen, "H102", raw, f"«{raw}»: единицу толщины не пишут", pg, bb)
        stages = [(c, _stage(c)) for c in toks]
        stages = [(c, s) for c, s in stages if s is not None]
        for (c1, s1), (c2, s2) in zip(stages, stages[1:]):
            if s2 < s1 and not (s1 == 2 and s2 == 2):
                once(drw, seen, "H103", raw, f"«{raw}»: «{c2}» стоит после «{c1}» — порядок: обработка основного металла, способ "
                     f"получения, материал и толщина, свойства, дополнительная обработка", pg, bb)
                break
        for i, c in enumerate(comps):
            if c.lower() == "лкп" and i > 0 and comps[i - 1] != "/":
                once(drw, seen, "H104", raw, f"«{raw}»: лакокрасочное покрытие отделяют чертой дроби — «…/лкп»", pg, bb)
        low = [c.lower() for c in toks]
