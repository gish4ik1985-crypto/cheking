TOKEN = re.compile(r"([A-Za-zА-Яа-яЁё]{1,6})(\d+(?:[.,]\d+)?)?")


def _designations(drw: Drawing):
    """(строки-компоненты, исходный текст, страница, рамка) для обозначений после слова «Покрытие»."""
    for t, pg, bb in texts(drw):
        for m in re.finditer(r"[Пп]окрыти\w*\s*[:\-–—]?\s*", t):
            s = t[m.end():]
            comps: list[str] = []
            pos = 0
            raw_end = 0
            while pos < len(s):
                tm = TOKEN.match(s, pos)
                if not tm:
                    break
                word = tm.group(1)
                known = word.lower() in PRE | METHOD | ADD | FUNC | DECOR | {"окс", "фос", "пас", "бцв", "хаки"} or word in METAL \
                    or word.upper().startswith("ПОС")
                if not known and not tm.group(2) and len(word) > 3:
                    break                               # обычное слово, а не составляющая обозначения
                if not known and not tm.group(2):
                    break
                comps.append(tm.group(0))
                raw_end = tm.end()
                nxt = s[raw_end:raw_end + 3]
                if nxt[:1] == "." and (nxt[1:2].isalpha() or nxt[1:3].strip().isalpha()):
                    pos = raw_end + 1
                    while pos < len(s) and s[pos] == " ":
                        pos += 1
                    continue
                if nxt[:1] == "/":
                    comps.append("/")
                    pos = raw_end + 1
                    continue
                break
            if comps and any(c != "/" for c in comps):
                yield comps, s[:raw_end], pg, bb


def _stage(tok: str) -> int | None:
    m = TOKEN.fullmatch(tok)
    if not m:
        return None
    w, num = m.group(1), m.group(2)
    low = w.lower()
    if num:
        return 2
    if w in ("Окс", "Фос"):
        return 2
    if low == "пас":
        return None
    if low in PRE and low not in ("ж", "м"):
        return 0
    if low in METHOD and w[0].isupper():
        return 1
    if low in ADD:
        return 4
    if low in FUNC or low in DECOR:
        return 3
    if w in METAL:
        return 2
    return None


